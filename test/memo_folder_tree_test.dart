import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:weaver/features/inbox/element_store.dart';
import 'package:weaver/features/inbox/graph_layout.dart';
import 'package:weaver/features/inbox/memo_boxes.dart';
import 'package:weaver/features/inbox/memo_folder_region.dart';
import 'package:weaver/features/inbox/memo_box_region.dart';
import 'package:weaver/features/inbox/thought_page.dart';
import 'package:weaver/features/inbox/thought_interaction.dart';
import 'package:weaver/features/inbox/workspace_menu.dart';
import 'package:weaver/features/inbox/workspace_storage.dart';

void main() {
  setUp(() { elements.clear(); memoBoxes.clear(); memoBoxFolders.clear(); memoBoxFolderParents.clear(); pageGraphLayout = GraphLayout(); });
  testWidgets('folders separate on release without moving the stationary folder', (tester) async {
    memoBoxFolders.addAll(['첫 폴더', '둘째 폴더']);
    final layout = pageGraphLayout.blockLayout;
    layout.folderPositions.addAll({'첫 폴더': const Offset(640, 400), '둘째 폴더': const Offset(1100, 400)});
    await tester.pumpWidget(MaterialApp(home: ThoughtPage(blocks: true, onChanged: () {})));
    await tester.pumpAndSettle();
    MemoFolderRegion folder(String name) => tester.widget<MemoFolderRegion>(find.byKey(ValueKey('folder-region-$name')));
    final fixed = folder('둘째 폴더').bounds;
    folder('첫 폴더').onMove(fixed.center - folder('첫 폴더').bounds.center); await tester.pump();
    expect(folder('첫 폴더').bounds.overlaps(fixed), isTrue);
    folder('첫 폴더').onEnd(); await tester.pumpAndSettle();
    expect(folder('첫 폴더').bounds.overlaps(fixed), isFalse);
    expect(folder('둘째 폴더').bounds, fixed);
    await tester.pumpWidget(const SizedBox());
  });
  testWidgets('a loose box separates from folders and a lifted box can leave its folder', (tester) async {
    memoBoxFolders.add('폴더');
    final a = elements.add('안쪽 생각'), b = elements.add('바깥 생각');
    final inside = MemoBox('안쪽', folder: '폴더', ids: [a.id]), outside = MemoBox('바깥', ids: [b.id]);
    memoBoxes.addAll([inside, outside]);
    pageGraphLayout.blockLayout.positions.addAll({a.id: const Offset(640, 400), b.id: const Offset(1200, 400)});
    var changes = 0;
    await tester.pumpWidget(MaterialApp(home: ThoughtPage(blocks: true, onChanged: () => changes++)));
    await tester.pumpAndSettle();
    MemoBoxRegion box(String name) => tester.widget<MemoBoxRegion>(find.byKey(ValueKey('box-region-$name')));
    Rect folderBounds() => tester.widget<MemoFolderRegion>(find.byKey(const ValueKey('folder-region-폴더'))).bounds;
    box('바깥').onDrag!(folderBounds().center - box('바깥').bounds.center); await tester.pump();
    box('바깥').onDragEnd!(); await tester.pumpAndSettle();
    expect(box('바깥').bounds.overlaps(folderBounds()), isFalse);
    final pointer = tester.getCenter(find.byKey(const ValueKey('box-region-안쪽')));
    box('안쪽').onLiftStart!(pointer); await tester.pump();
    box('안쪽').onLiftMove!(pointer + const Offset(0, 700)); await tester.pump();
    box('안쪽').onDragEnd!(); await tester.pumpAndSettle();
    expect(inside.folder, isNull);
    expect(inside.elementIds, {a.id});
    final destination = tester.getTopLeft(find.byKey(const ValueKey('folder-region-폴더'))) + const Offset(12, 12);
    final origin = tester.getCenter(find.byKey(const ValueKey('box-region-안쪽')));
    box('안쪽').onLiftStart!(origin); await tester.pump();
    box('안쪽').onLiftMove!(destination); await tester.pump();
    box('안쪽').onLiftEnd!(destination); await tester.pumpAndSettle();
    expect(inside.folder, '폴더');
    expect(inside.elementIds, {a.id});
    expect(changes, greaterThan(0));
    await tester.pumpWidget(const SizedBox());
  });
  testWidgets('folder title has no modal and lifted folders nest and detach', (tester) async {
    memoBoxFolders.addAll(['이동 폴더', '대상 폴더']);
    final layout = pageGraphLayout.blockLayout;
    layout.folderPositions.addAll({'이동 폴더': const Offset(640, 400), '대상 폴더': const Offset(1100, 400)});
    final record = elements.add('상자 생각');
    final box = MemoBox('상자', ids: [record.id]); memoBoxes.add(box);
    layout.positions[record.id] = const Offset(1700, 400);
    await tester.pumpWidget(MaterialApp(home: ThoughtPage(blocks: true, onChanged: () {})));
    await tester.pumpAndSettle();
    MemoFolderRegion folder(String name) => tester.widget<MemoFolderRegion>(find.byKey(ValueKey('folder-region-$name')));
    Offset center(String name) => tester.getCenter(find.byKey(ValueKey('folder-region-$name')));
    await tester.tap(find.text('이동 폴더')); await tester.pumpAndSettle();
    expect(find.byType(AlertDialog), findsNothing);
    final target = center('대상 폴더');
    folder('이동 폴더').onLiftStart!(center('이동 폴더')); await tester.pump();
    folder('이동 폴더').onLiftMove!(target); await tester.pump();
    folder('이동 폴더').onLiftEnd!(target); await tester.pumpAndSettle();
    expect(memoFolderParent('이동 폴더'), '대상 폴더');
    expect(canMoveMemoFolder('대상 폴더', '이동 폴더'), isFalse);
    final from = center('이동 폴더'), outside = from + const Offset(0, 700);
    folder('이동 폴더').onLiftStart!(from); await tester.pump();
    folder('이동 폴더').onLiftMove!(outside); await tester.pump();
    folder('이동 폴더').onLiftEnd!(outside); await tester.pumpAndSettle();
    expect(memoFolderParent('이동 폴더'), isNull);
    final before = folder('이동 폴더').bounds;
    final boxCenter = tester.getCenter(find.byKey(const ValueKey('box-region-상자')));
    folder('이동 폴더').onLiftStart!(center('이동 폴더')); await tester.pump();
    folder('이동 폴더').onLiftMove!(boxCenter); await tester.pump();
    folder('이동 폴더').onLiftEnd!(boxCenter); await tester.pumpAndSettle();
    expect(folder('이동 폴더').bounds.left, closeTo(before.left, .01));
    expect(folder('이동 폴더').bounds.top, closeTo(before.top, .01));
    expect(memoFolderParent('이동 폴더'), isNull);
    expect(box.elementIds, {record.id});
    await tester.pumpWidget(const SizedBox());
  });
  test('folder tree persists independently of box and thought ownership', () {
    final thought = elements.add('상자에만 담긴 생각');
    memoBoxFolders.addAll(['부모', '자식', '손자']);
    moveMemoFolder('자식', '부모'); moveMemoFolder('손자', '자식');
    memoBoxes.add(MemoBox('자료', folder: '손자', ids: [thought.id]));
    expect(() => moveMemoFolder('부모', '손자'), throwsArgumentError);
    final snapshot = WorkspaceSnapshot.decode(WorkspaceSnapshot.encode([]));
    memoBoxFolderParents.clear(); snapshot.apply();
    expect(memoFolderPath('손자'), '부모 / 자식 / 손자');
    expect(memoBoxes.singleWhere((b) => b.name == '자료').elementIds, {thought.id});
    moveMemoFolder('자식', null); expect(memoFolderPath('손자'), '자식 / 손자');
  });
  testWidgets('menu folder drops change shared data and reject descendants', (tester) async {
    memoBoxFolders.addAll(['부모', '자식']); var changes = 0;
    await tester.pumpWidget(MaterialApp(theme: ThemeData(platform: TargetPlatform.linux), home: Scaffold(
      body: WorkspaceMenu(embedded: true, projects: const [], onBoxChanged: () => changes++))));
    await tester.pumpAndSettle();
    final target = tester.widget<DragTarget<MemoFolderDrag>>(find.byKey(const ValueKey('drop-folder-부모')));
    final details = DragTargetDetails(data: const MemoFolderDrag('자식'), offset: Offset.zero);
    expect(target.onWillAcceptWithDetails!(details), isTrue);
    target.onAcceptWithDetails!(details); await tester.pumpAndSettle();
    expect(memoFolderParent('자식'), '부모'); expect(changes, 1);
    expect(canMoveMemoFolder('부모', '자식'), isFalse);
    final outside = tester.widget<DragTarget<MemoFolderDrag>>(find.byKey(const ValueKey('drop-folder-outside')));
    outside.onAcceptWithDetails!(details); await tester.pumpAndSettle();
    expect(memoFolderParent('자식'), isNull);
    await tester.pumpWidget(const SizedBox());
  });
  testWidgets('folder canvas encloses shared boxes but never owns thoughts', (tester) async {
    final thought = elements.add('자료 메모'), loose = elements.add('폴더에 넣을 수 없는 메모');
    memoBoxFolders.addAll(['상위', '하위', '빈폴더']); moveMemoFolder('하위', '상위');
    final box = MemoBox('자료', folder: '하위', ids: [thought.id]); memoBoxes.add(box);
    await tester.pumpWidget(MaterialApp(home: ThoughtPage(blocks: true, onChanged: () {})));
    await tester.pumpAndSettle();
    final outer = tester.widget<MemoFolderRegion>(find.byKey(const ValueKey('folder-region-상위')));
    final inner = tester.widget<MemoFolderRegion>(find.byKey(const ValueKey('folder-region-하위')));
    final region = tester.widget<MemoBoxRegion>(find.byKey(const ValueKey('box-region-자료')));
    expect(outer.bounds.contains(inner.bounds.topLeft), isTrue);
    expect(inner.bounds.contains(region.bounds.topLeft), isTrue);
    expect(find.descendant(of: find.byType(MemoFolderRegion), matching: find.byType(DragTarget<MemoDrag>)), findsNothing);
    outer.onMove(const Offset(40, 30)); outer.onEnd(); await tester.pumpAndSettle();
    final moved = tester.widget<MemoBoxRegion>(find.byKey(const ValueKey('box-region-자료')));
    expect(moved.bounds.topLeft, region.bounds.topLeft + const Offset(40, 30));
    expect(box.elementIds, {thought.id});
    expect(memoBoxes.any((b) => !b.isUnclassified && b.elementIds.contains(loose.id)), isFalse);
    expect(memoBoxes.where((b) => !b.isUnclassified).length, 1);
    final interaction = tester.widget<ThoughtInteraction>(find.ancestor(of: find.text(loose.text), matching: find.byType(ThoughtInteraction)).first);
    final origin = pageGraphLayout.blockLayout.positions[loose.id]!;
    interaction.onActiveChanged!(true);
    interaction.onMove(const Offset(100, 100)); await tester.pump();
    final empty = find.byKey(const ValueKey('folder-region-빈폴더'));
    interaction.onDrop(tester.getCenter(empty)); interaction.onEnd(); await tester.pumpAndSettle();
    expect(pageGraphLayout.blockLayout.positions[loose.id], origin);
    expect(box.elementIds, {thought.id});
    expect(tester.takeException(), isNull);
    await tester.pumpWidget(const SizedBox());
  });
}
